<h4>B. Legalitas Madrasah Tsanawiyah Sunan Kalijaga Tulung</h4>
Pada tanggal 1 Januari 1970, MTs. Sunan Kalijaga Tulung, menerima Piagam Pendirian Madrasah yang ditandatangani oleh Drs. H. Moh. Rifa’i, selaku Kepala Bidang Pendidikan Agama Islam Kanwil Depag Propinsi Jawa Tengah, dengan nomor: 2/B./V/1970.
Pada tahun 2006, MTs. Sunan Kalijaga Tulung diadakan penilaian atau akreditasi oleh Badan Akreditasi Nasional dengan peringkat baik (Tipe B), sesuai dengan nomor Akreditasi: Kw.II.4/4/PP.03.2/623.10.16/2006. Dan pada tahun 2012 ini, kembali MTs Sunan Kalijaga akan diakreditasi oleh Badan Akreditasi Nasional, yang Alhamdulillah sudah dilaksanakan pada tanggal 10 s.d. 11 Agustus 2012, dan pada tanggal 11 s.d. 13 Agustus 2018, untuk ketiga kalinya  Sunan Kalijaga Tulung, kembali diakreditasi oleh Badan Akreditasi Nasional, dan Alhamdulillah terakreditasi dengan Tipe B, dengan hasil tersebut MTs. Sunan Kalijaga Tulung tetap memiliki harapan, agar ke depannya, MTs. Sunan Kalijaga Tulung menjadi sebuah sekolah yang berbasis unggulan dengan Peringkat B.

