	<h4>A. Latar Belakang Berdirinya Madrasah Tsanawiyah Sunan Kalijaga Tulung</h4>
Madrasah Tsanawiyah Sunan Kalijaga Tulung adalah sebuah lembaga pendidikan setingkat Sekolah Dasar yang memasukkan pendidikan agama sebagai ciri khas dan pendidikan plus dalam melaksanakan pembelajaran dan pelaksanaan pengembangan kurikulum di dalamnya. Dalam perjalanan panjangnya, MTs. Sunan Kalijaga Tulung memiliki sejarah yang sangat unik dan berliku.
Adapun sejarah mengenai MTs. Sunan Kalijaga Tulung ini, akan kami paparkan dalam serangkaian cerita mengenai, berikut kami paparkan sejarah mengenai MTs. Sunan Kalijaga Tulung dengan informasi dari berbagai sumber, baik dari pelaku maupun saksi yang masih hidup dalam menghiasi perjalanan MTs. Sunan Kalijaga Tulung.
Sebelum bernama MTs. Sunan Kalijaga Tulung, pada tanggal 1 Januari 1969, sudah berdiri sebuah madrasah yang diberi nama Madrasah Tadrisiyah Sunan Kalijaga, yang merupakan cikal bakal dari MTs. Sunan Kalijaga Tulung. Pada masa itu Madrasah Tadrisiyah Sunan Kalijaga Tulung beroperasi dan melaksanakan Proses Belajar Mengajar pada waktu sore hari, mulai pukul 15.30 sd 16.30 wib., dengan perpedoman pada kurikulum Pondok Pesantren. Pada tahun 1970, Madrasah Tadrisiyah Sunan Kalijaga Tulung berganti nama menjadi Madrasah Tsanawiyah Sunan Kalijaga Tulung, dengan Kepala Madrasah yang pertama adalah Bp. Muhammad Thoha dari Ngunut, Pucangmiliran, Tulung, Klaten.

